#!/usr/bin/env python3
"""
convert_to_c_array.py — TFLite → C byte array for firmware embedding

Converts model.tflite to model_data.h and copies it to the firmware directory.

Usage:
    python convert_to_c_array.py

This is the final step in the sensor model pipeline.
After running this, set USE_TINYML=1 in platformio.ini and reflash.
"""

import struct
import shutil
from pathlib import Path
import yaml

CONFIG_PATH = Path(__file__).parent.parent / "configs" / "train_config.yaml"
with open(CONFIG_PATH) as f:
    cfg = yaml.safe_load(f)

VAR_NAME       = cfg["export"]["c_array_var_name"]
TFLITE_PATH    = Path(__file__).parent / "model.tflite"
# BUG WAS: Path(cfg[...]).resolve() — resolves relative to CWD, breaks if not run from script dir
# FIX: anchor relative path to script location (__file__), then resolve
_SCRIPT_DIR    = Path(__file__).parent
FIRMWARE_PATH  = (_SCRIPT_DIR / cfg["export"]["output_c_array"]).resolve()
FIRMWARE_PATH.parent.mkdir(parents=True, exist_ok=True)


def to_c_array(data: bytes, var_name: str) -> str:
    lines = [
        "/**",
        " * model_data.h — AUTO-GENERATED by convert_to_c_array.py",
        f" * Model size: {len(data)} bytes ({len(data)/1024:.1f} KB)",
        " * DO NOT EDIT MANUALLY",
        " */",
        "#pragma once",
        "",
        f"const unsigned char {var_name}[] = {{",
    ]
    # 12 bytes per line
    for i in range(0, len(data), 12):
        chunk = data[i:i+12]
        hex_vals = ", ".join(f"0x{b:02x}" for b in chunk)
        lines.append(f"    {hex_vals},")
    lines.append("};")
    lines.append(f"const unsigned int {var_name}_len = {len(data)};")
    lines.append("")
    return "\n".join(lines)


def main():
    if not TFLITE_PATH.exists():
        print(f"[C-Array] model.tflite not found at {TFLITE_PATH}")
        print("  Run quantize_int8.py first.")
        return

    data = TFLITE_PATH.read_bytes()
    print(f"[C-Array] Read {len(data)} bytes from {TFLITE_PATH}")

    c_src = to_c_array(data, VAR_NAME)

    # Write to firmware directory
    FIRMWARE_PATH.write_text(c_src, encoding="utf-8")
    print(f"[C-Array] Written → {FIRMWARE_PATH}")
    print(f"\nNext steps:")
    print(f"  1. Set USE_TINYML=1 in firmware/esp32_sensor_node/platformio.ini")
    print(f"  2. Rebuild and flash: pio run -e esp32_sensor_node --target upload")


if __name__ == "__main__":
    main()
