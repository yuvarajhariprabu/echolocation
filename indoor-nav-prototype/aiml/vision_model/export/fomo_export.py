#!/usr/bin/env python3
"""
fomo_export.py — Download & Convert Edge Impulse FOMO Model for Firmware

Downloads the trained FOMO model from Edge Impulse as an Arduino library,
extracts the model .tflite, converts it to a C byte array, and copies it
into the esp32_cam_node firmware directory.

Prerequisites:
    pip install edge-impulse-cli requests
    ei login   (authenticate with your Edge Impulse account)

Usage:
    python fomo_export.py --project-id <your-EI-project-id>
"""

import argparse
import os
import subprocess
import zipfile
import tempfile
import shutil
from pathlib import Path

FIRMWARE_MODEL_PATH = Path(__file__).parent.parent.parent.parent / \
    "firmware" / "esp32_cam_node" / "src" / "inference" / "fomo_model_data.h"

VAR_NAME = "g_fomo_model_data"


def to_c_array(data: bytes, var_name: str) -> str:
    lines = [
        "/**",
        " * fomo_model_data.h — AUTO-GENERATED by fomo_export.py",
        f" * Model size: {len(data)} bytes ({len(data)/1024:.1f} KB)",
        " * DO NOT EDIT MANUALLY — re-run fomo_export.py after retraining",
        " */",
        "#pragma once",
        "",
        f"const unsigned char {var_name}[] = {{",
    ]
    for i in range(0, len(data), 12):
        chunk = data[i:i+12]
        hex_vals = ", ".join(f"0x{b:02x}" for b in chunk)
        lines.append(f"    {hex_vals},")
    lines.append("};")
    lines.append(f"const unsigned int {var_name}_len = {len(data)};")
    lines.append("")
    return "\n".join(lines)


def export_via_cli(project_id: str):
    print(f"[FOMO Export] Exporting project {project_id} via Edge Impulse CLI...")
    with tempfile.TemporaryDirectory() as tmpdir:
        cmd = [
            "edge-impulse-export",
            "--project-id", str(project_id),
            "--type", "tflite",
            "--output-dir", tmpdir,
        ]
        result = subprocess.run(cmd, capture_output=True, text=True)
        if result.returncode != 0:
            print(f"[FOMO Export] CLI error:\n{result.stderr}")
            print("  Make sure you have run: ei login")
            return

        # Find .tflite file in output
        tflite_files = list(Path(tmpdir).rglob("*.tflite"))
        if not tflite_files:
            print("[FOMO Export] No .tflite found in export output.")
            return

        tflite_path = tflite_files[0]
        data = tflite_path.read_bytes()
        print(f"[FOMO Export] Found model: {tflite_path.name}  ({len(data)/1024:.1f} KB)")

        c_src = to_c_array(data, VAR_NAME)
        FIRMWARE_MODEL_PATH.write_text(c_src, encoding="utf-8")
        print(f"[FOMO Export] Written → {FIRMWARE_MODEL_PATH}")
        print("\nNext: rebuild esp32_cam_node and flash.")


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--project-id", required=True, help="Edge Impulse project ID")
    args = parser.parse_args()
    export_via_cli(args.project_id)


if __name__ == "__main__":
    main()
